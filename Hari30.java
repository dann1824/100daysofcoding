public class Hari30 {
    public static void main(String[] args) {


        int angka = 10;
        System.out.println("--------------------------------------------------");
        System.out.println("=== MENGGUNAKAN OPERATOR SAMA ATAU TIDAK SAMA ===");

        // Contoh 1 <= (Kurang dari atau sama dengan)
        System.out.println(angka <= 15); 
        System.out.println(angka <= 10); 

        // Contoh >= (Lebih dari atau sama dengan)
        System.out.println(angka >= 20); 
        System.out.println(angka >= 10);
        
        System.out.println("--------------------------------------------------");

    }
          }
