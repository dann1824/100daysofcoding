
public class DayXXVII {
    
    public static void main(String[] args) {
        
        
       System.out.println("=== MENGGUNAKAN INCREMENT DAN DECREMENT ==="); 
        int a = 20;
        int b = 30;
        
        a++;
        b++;
        
        System.out.println("increment: a = " + a + ", b = " + b );
        
        a--;
        b--;
        
        System.out.println("decrement: a = " + a + ", b = " + b );
           
        
    }
    
}
